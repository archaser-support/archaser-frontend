#!/usr/bin/env node
/**
 * Emits `types/db.ts` from the Nest `prisma/schema.prisma`.
 *
 * The frontend is UI-only and talks to Nest over HTTP, so it owns plain
 * structural types instead of depending on a generated Prisma client. Run this
 * from the monorepo (schema present) and commit the result; the standalone
 * frontend repo builds from the committed file.
 *
 * Usage: node scripts/generate-db-types.js [--schema <path>] [--check]
 */
const fs = require("fs");
const path = require("path");

const SCALARS = {
    String: "string",
    Boolean: "boolean",
    Int: "number",
    BigInt: "bigint",
    Float: "number",
    Decimal: "Decimal",
    DateTime: "Date",
    Json: "JsonValue",
    Bytes: "Uint8Array",
};

function parseArgs(argv) {
    const args = { check: false, schema: null };
    for (let i = 0; i < argv.length; i += 1) {
        if (argv[i] === "--check") args.check = true;
        if (argv[i] === "--schema") args.schema = argv[i + 1];
    }
    return args;
}

function stripComments(line) {
    const idx = line.indexOf("//");
    return (idx >= 0 ? line.slice(0, idx) : line).trim();
}

function parseSchema(source) {
    const enums = [];
    const models = [];
    const lines = source.split(/\r?\n/);
    let block = null;

    for (const raw of lines) {
        const line = stripComments(raw);
        if (!line) continue;

        if (!block) {
            const enumMatch = line.match(/^enum\s+(\w+)\s*\{/);
            if (enumMatch) {
                block = { kind: "enum", name: enumMatch[1], members: [] };
                continue;
            }
            const modelMatch = line.match(/^model\s+(\w+)\s*\{/);
            if (modelMatch) {
                block = { kind: "model", name: modelMatch[1], fields: [] };
            }
            continue;
        }

        if (line === "}") {
            if (block.kind === "enum") enums.push(block);
            else models.push(block);
            block = null;
            continue;
        }

        if (block.kind === "enum") {
            const member = line.match(/^(\w+)/);
            if (member) block.members.push(member[1]);
            continue;
        }

        if (line.startsWith("@@")) continue;
        const field = line.match(/^(\w+)\s+(Unsupported\("[^"]*"\)|[\w.]+)(\[\])?(\?)?/);
        if (!field) continue;
        block.fields.push({
            name: field[1],
            type: field[2],
            list: Boolean(field[3]),
            optional: Boolean(field[4]),
        });
    }

    return { enums, models };
}

function tsType(field, enumNames, modelNames) {
    const { type } = field;
    if (type.startsWith("Unsupported(")) return "unknown";
    if (SCALARS[type]) return SCALARS[type];
    if (enumNames.has(type) || modelNames.has(type)) return type;
    return "unknown";
}

function renderField(field, base) {
    if (field.list) return `${field.name}: ${base}[];`;
    return `${field.name}: ${base}${field.optional ? " | null" : ""};`;
}

function generate(schemaPath) {
    const { enums, models } = parseSchema(fs.readFileSync(schemaPath, "utf8"));
    const enumNames = new Set(enums.map((e) => e.name));
    const modelNames = new Set(models.map((m) => m.name));

    const out = [];
    out.push("/**");
    out.push(" * Generated by `npm run generate:db-types` from the Nest prisma schema.");
    out.push(" * Do not edit by hand — rerun the script when the schema changes.");
    out.push(" *");
    out.push(" * These mirror the API row shapes the frontend receives from Nest. They are");
    out.push(" * plain structural types: no Prisma client, no database access.");
    out.push(" */");
    out.push("");
    out.push("/* eslint-disable @typescript-eslint/no-explicit-any */");
    out.push("");
    out.push("export type JsonValue =");
    out.push("    | string");
    out.push("    | number");
    out.push("    | boolean");
    out.push("    | null");
    out.push("    | JsonValue[]");
    out.push("    | { [key: string]: JsonValue };");
    out.push("");
    out.push("/** Prisma `Decimal` columns arrive as JSON numbers (or strings for wide values). */");
    out.push("export type Decimal = number | string;");
    out.push("");

    for (const e of enums.sort((a, b) => a.name.localeCompare(b.name))) {
        out.push(`export const ${e.name} = {`);
        for (const member of e.members) {
            out.push(`    ${member}: "${member}",`);
        }
        out.push("} as const;");
        out.push(
            `export type ${e.name} = (typeof ${e.name})[keyof typeof ${e.name}];`
        );
        out.push("");
    }

    for (const model of models.sort((a, b) => a.name.localeCompare(b.name))) {
        const scalars = model.fields.filter((f) => !modelNames.has(f.type));
        const relations = model.fields.filter((f) => modelNames.has(f.type));

        out.push(`export interface ${model.name} {`);
        for (const field of scalars) {
            out.push(
                `    ${renderField(field, tsType(field, enumNames, modelNames))}`
            );
        }
        out.push("}");
        out.push("");

        if (relations.length > 0) {
            out.push(`export interface ${model.name}Relations {`);
            for (const field of relations) {
                out.push(`    ${renderField(field, field.type)}`);
            }
            out.push("}");
            out.push("");
        }
    }

    return `${out.join("\n").replace(/\n+$/, "")}\n`;
}

function main() {
    const args = parseArgs(process.argv.slice(2));
    const schemaPath = path.resolve(
        args.schema || path.join(__dirname, "../../backend/prisma/schema.prisma")
    );
    const target = path.join(__dirname, "../types/db.ts");

    if (!fs.existsSync(schemaPath)) {
        console.info(
            `[generate-db-types] No schema at ${schemaPath} — keeping committed types/db.ts`
        );
        process.exit(0);
    }

    const generated = generate(schemaPath);
    const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";

    if (args.check) {
        if (current !== generated) {
            console.error(
                "[generate-db-types] types/db.ts is stale — run `npm run generate:db-types`"
            );
            process.exit(1);
        }
        console.info("[generate-db-types] types/db.ts is up to date");
        return;
    }

    fs.writeFileSync(target, generated);
    console.info(`[generate-db-types] wrote ${path.relative(process.cwd(), target)}`);
}

main();
